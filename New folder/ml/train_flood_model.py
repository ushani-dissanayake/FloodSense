"""Train, evaluate, and save FloodSense models from Data_Set/flood_data.csv.

Saves:
  ml/models/flood_risk_rf.joblib
  ml/models/flood_risk_tree.joblib
  ml/models/anomaly_iforest.joblib
  ml/models/flood_model.json
  FloodSense-Kotlin-Android/.../assets/flood_model.json

Run from the FloodSense folder:

    python3 -m pip install -r ml/requirements.txt
    python3 ml/train_flood_model.py
"""

from __future__ import annotations

import json
from pathlib import Path

import joblib
import pandas as pd
from sklearn.ensemble import IsolationForest, RandomForestClassifier
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier, export_text

ROOT = Path(__file__).resolve().parents[1]
CSV_PATH = ROOT / "Data_Set" / "flood_data.csv"
MODEL_DIR = ROOT / "ml" / "models"
ASSET_PATH = (
    ROOT
    / "FloodSense-Kotlin-Android-Starter"
    / "FloodSense-Kotlin-Android"
    / "app"
    / "src"
    / "main"
    / "assets"
    / "flood_model.json"
)


def main() -> None:
    MODEL_DIR.mkdir(parents=True, exist_ok=True)
    ASSET_PATH.parent.mkdir(parents=True, exist_ok=True)

    frame = pd.read_csv(CSV_PATH)
    features = ["water_level", "rainfall", "temperature", "humidity"]
    x_risk = frame[["water_level", "rainfall"]]
    y = frame["flood_risk"].astype(int)
    x_all = frame[features]

    x_train, x_test, y_train, y_test = train_test_split(
        x_risk, y, test_size=0.25, random_state=42, stratify=y
    )

    forest = RandomForestClassifier(n_estimators=80, max_depth=8, random_state=42)
    forest.fit(x_train.to_numpy(), y_train)
    forest_pred = forest.predict(x_test.to_numpy())
    forest_acc = float(accuracy_score(y_test, forest_pred))

    tree = DecisionTreeClassifier(max_depth=5, min_samples_leaf=15, random_state=42)
    tree.fit(x_train.to_numpy(), y_train)
    tree_pred = tree.predict(x_test.to_numpy())
    tree_acc = float(accuracy_score(y_test, tree_pred))

    anomaly = IsolationForest(contamination=0.06, random_state=42)
    anomaly.fit(x_all.to_numpy())

    joblib.dump(forest, MODEL_DIR / "flood_risk_rf.joblib")
    joblib.dump(tree, MODEL_DIR / "flood_risk_tree.joblib")
    joblib.dump(anomaly, MODEL_DIR / "anomaly_iforest.joblib")

    report = classification_report(y_test, forest_pred, digits=3, output_dict=True)
    matrix = confusion_matrix(y_test, forest_pred).tolist()

    # Leaf-class probability by predicted class on the held-out set.
    class_probability = {}
    proba = forest.predict_proba(x_test.to_numpy())
    for label in forest.classes_:
        mask = forest_pred == label
        if mask.any():
            class_probability[str(int(label))] = float(proba[mask][:, list(forest.classes_).index(label)].mean())
        else:
            class_probability[str(int(label))] = {0: 0.18, 1: 0.62, 2: 0.88}[int(label)]

    bounds = {
        column: {
            "min": float(frame[column].min()),
            "max": float(frame[column].max()),
            "p01": float(frame[column].quantile(0.01)),
            "p99": float(frame[column].quantile(0.99)),
        }
        for column in features
    }

    payload = {
        "dataset": "Data_Set/flood_data.csv",
        "rows": int(len(frame)),
        "risk_features": ["water_level", "rainfall"],
        "anomaly_features": features,
        "synthetic_holdout_accuracy": round(forest_acc, 4),
        "random_forest_accuracy": round(forest_acc, 4),
        "decision_tree_accuracy": round(tree_acc, 4),
        "accuracy_note": (
            "Hold-out accuracy on flood_data.csv is not field performance. "
            "Those labels are generated by the same water/rain thresholds the tree recovered. "
            "See field_validation.json for Irrigation Department / DMC gauge validation."
        ),
        "class_probability": class_probability,
        "confusion_matrix": matrix,
        "classification_report": report,
        "tree_rules": {
            "high_rainfall_mm": 200.0,
            "high_water_m": 8.0,
            "medium_rainfall_mm": 59.97,
            "medium_water_m": 4.97,
        },
        "tree_text": export_text(tree, feature_names=["water_level", "rainfall"]),
        "anomaly_bounds": bounds,
        "decisions": {
            "ISSUE_ALERT": "High flood risk — notify citizens immediately",
            "WATCH": "Medium risk or anomaly — keep monitoring",
            "FLAG_SENSOR": "Sensor/station anomaly — check the device",
            "NORMAL": "Low risk and healthy sensors",
        },
    }

    model_json = MODEL_DIR / "flood_model.json"
    model_json.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    ASSET_PATH.write_text(json.dumps(payload, indent=2), encoding="utf-8")

    print("Random Forest accuracy:", round(forest_acc, 4))
    print("Decision tree accuracy:", round(tree_acc, 4))
    print("Confusion matrix:", matrix)
    print(classification_report(y_test, forest_pred, digits=3))
    print(export_text(tree, feature_names=["water_level", "rainfall"]))
    print("Saved:")
    for path in sorted(MODEL_DIR.iterdir()):
        print(" ", path)
    print(" ", ASSET_PATH)


if __name__ == "__main__":
    main()
